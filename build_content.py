AR_DIGITS = "٠١٢٣٤٥٦٧٨٩"
def ar(n): return "".join(AR_DIGITS[int(c)] for c in str(n))

POSTER_DIR = "docs/posters"
# بيانات مصادر الملصقات: slug -> (نص المصدر والترخيص، الرابط)
POSTER_CREDITS = {}

def poster_of(f):
    for ext in ("webp", "jpg", "jpeg", "png"):
        if os.path.exists(f"{POSTER_DIR}/{f['slug']}.{ext}"):
            return f"{f['slug']}.{ext}"
    return None

def film_page(f):
    rows = [("السنة", ar(f["year"])), ("الإخراج", f["director"]), ("التأليف", f["writer"]),
            ("التمثيل", f["cast"]), ("الإنتاج", f["producer"]), ("المدة", f["duration"]),
            ("العرض الأول", f["premiere"])]
    meta = "\n".join(f'<div class="meta-row"><span>{k}</span><b>{v}</b></div>' for k, v in rows if v)
    src = "\n".join(f"- [{t}]({u})" for t, u in f["sources"])
    poster = poster_of(f)
    poster_html = ""
    if poster:
        credit = POSTER_CREDITS.get(f["slug"])
        cap = f'<figcaption>المصدر: <a href="{credit[1]}">{credit[0]}</a></figcaption>' if credit else ""
        poster_html = (f'<figure class="film-poster"><img src="../../posters/{poster}" '
                       f'alt="ملصق فيلم {f["title"]}" loading="lazy">{cap}</figure>')
    return f"""---
title: {f['title']} ({ar(f['year'])})
---

<div class="film-top{' has-poster' if poster else ''}">
{poster_html}
<div class="film-hero">
<div class="film-year">{ar(f['year'])}</div>
<h1>{f['title']}</h1>
<div class="film-by">إخراج {f['director']}</div>
</div>
</div>

<div class="film-meta">
{meta}
</div>

## القصة

{f['story']}

## مكانته في السينما المصرية

{f['why']}

<div class="sources" markdown="1">

## المصادر

{src}

</div>
"""

def card(f, prefix):
    poster = poster_of(f)
    img = (f'<img class="fc-img" src="{prefix}posters/{poster}" alt="" loading="lazy">' if poster else "")
    cls = "film-card has-poster" if poster else "film-card"
    return (f'<a class="{cls}" href="{prefix}films/{f["slug"]}/">{img}'
            f'<span class="fc-year">{ar(f["year"])}</span>'
            f'<span class="fc-title">{f["title"]}</span>'
            f'<span class="fc-dir">{f["director"].split(" (")[0]}</span></a>')

os.makedirs("docs/films", exist_ok=True)
os.makedirs("docs/decades", exist_ok=True)
for f in FILMS:
    open(f"docs/films/{f['slug']}.md", "w", encoding="utf8").write(film_page(f))

